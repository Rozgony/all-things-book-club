// dueRecurringRule holds the columns needed to compute and insert the next occurrence.
type dueRecurringRule struct {
	ID        string
	ChapterID string
	Frequency string
	Interval  int
	Duration  int
	EndDate   *time.Time
}

// nextOccurrence advances lastScheduled by the rule's frequency/interval.
func nextOccurrence(lastScheduled time.Time, frequency string, interval int) time.Time {
	switch frequency {
	case "MINUTES":
		return lastScheduled.Add(time.Duration(interval) * time.Minute)
	case "DAILY":
		return lastScheduled.AddDate(0, 0, interval)
	case "WEEKLY":
		return lastScheduled.AddDate(0, 0, 7*interval)
	case "MONTHLY":
		return lastScheduled.AddDate(0, interval, 0)
	case "MONTHLY_WEEKDAY":
		return nextMonthlyWeekday(lastScheduled, interval)
	default:
		return lastScheduled.AddDate(0, 0, 7*interval)
	}
}

// nextMonthlyWeekday returns the same Nth occurrence of lastScheduled's weekday
// (e.g. the 1st Thursday), `interval` months later. If that occurrence doesn't
// exist in the target month (e.g. a 5th occurrence), it falls back to the last
// one that does.
func nextMonthlyWeekday(lastScheduled time.Time, interval int) time.Time {
	weekday := lastScheduled.Weekday()
	occurrence := (lastScheduled.Day()-1)/7 + 1

	totalMonths := int(lastScheduled.Month()) - 1 + interval
	year := lastScheduled.Year() + totalMonths/12
	month := time.Month(totalMonths%12 + 1)

	first := time.Date(year, month, 1, lastScheduled.Hour(), lastScheduled.Minute(),
		lastScheduled.Second(), lastScheduled.Nanosecond(), lastScheduled.Location())
	day := 1 + (int(weekday-first.Weekday()+7) % 7) + (occurrence-1)*7

	for {
		candidate := time.Date(year, month, day, lastScheduled.Hour(), lastScheduled.Minute(),
			lastScheduled.Second(), lastScheduled.Nanosecond(), lastScheduled.Location())
		if candidate.Month() == month {
			return candidate
		}
		day -= 7 // requested occurrence doesn't exist this month, use the last one
	}
}

// GenerateUpcomingOccurrences creates the next meeting for every recurring rule whose
// most recent meeting's computed next occurrence is due, copying the location blob
// forward (discussion notes intentionally start empty for the new occurrence).
func (s *RecurringRuleService) GenerateUpcomingOccurrences(ctx context.Context) error {
	rows, err := s.db.Query(ctx, `
		SELECT r.id, r.chapter_id, r.frequency, r.interval, r.duration, r.end_date,
			m.scheduled_at, m.location_encrypted_blob, m.location_nonce
		FROM recurring_rules r
		JOIN meetings m ON m.recurring_group_id = r.id
		WHERE m.scheduled_at = (
			SELECT MAX(scheduled_at) FROM meetings WHERE recurring_group_id = r.id
		)
	`)
	if err != nil {
		return fmt.Errorf("RecurringRuleService.GenerateUpcomingOccurrences: query due rules: %w", err)
	}
	defer rows.Close()

	type candidate struct {
		rule                  dueRecurringRule
		lastScheduled         time.Time
		locationEncryptedBlob []byte
		locationNonce         []byte
	}
	var candidates []candidate
	for rows.Next() {
		var c candidate
		if err := rows.Scan(&c.rule.ID, &c.rule.ChapterID, &c.rule.Frequency, &c.rule.Interval,
			&c.rule.Duration, &c.rule.EndDate, &c.lastScheduled, &c.locationEncryptedBlob, &c.locationNonce); err != nil {
			return fmt.Errorf("RecurringRuleService.GenerateUpcomingOccurrences: scan: %w", err)
		}
		candidates = append(candidates, c)
	}

	for _, c := range candidates {
		next := nextOccurrence(c.lastScheduled, c.rule.Frequency, c.rule.Interval)
		if next.After(time.Now().AddDate(0, 0, 14)) {
			continue // only generate occurrences within a 2-week lookahead window
		}
		if c.rule.EndDate != nil && next.After(*c.rule.EndDate) {
			continue // recurrence has ended
		}

		meetingID, err := crypto.GenerateID()
		if err != nil {
			return fmt.Errorf("RecurringRuleService.GenerateUpcomingOccurrences: generate meeting ID: %w", err)
		}

		_, err = s.db.Exec(ctx, `
			INSERT INTO meetings (id, chapter_id, scheduled_at, duration, status, recurring_group_id,
				location_encrypted_blob, location_nonce, created_at, updated_at)
			VALUES ($1, $2, $3, $4, 'SCHEDULED', $5, $6, $7, now(), now())
		`, meetingID, c.rule.ChapterID, next, c.rule.Duration, c.rule.ID, c.locationEncryptedBlob, c.locationNonce)
		if err != nil {
			return fmt.Errorf("RecurringRuleService.GenerateUpcomingOccurrences: insert meeting for rule %s: %w", c.rule.ID, err)
		}
	}

	return nil
}
