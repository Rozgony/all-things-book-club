type RecurringRuleService struct {
	db *pgxpool.Pool
}

// ErrRecurringRuleExists is returned when a chapter already has an active recurring rule.
var ErrRecurringRuleExists = errors.New("chapter already has an active recurring rule")

func NewRecurringRuleService(db *pgxpool.Pool) *RecurringRuleService {
	return &RecurringRuleService{db: db}
}

// GetDB returns the database pool for use in route handlers
func (s *RecurringRuleService) GetDB() *pgxpool.Pool {
	return s.db
}

// RecurringRuleInput is the data the client sends when scheduling a recurring meeting series.
type RecurringRuleInput struct {
	ChapterID             string     `json:"chapterId"`
	Frequency             string     `json:"frequency"`
	Interval              int        `json:"interval"`
	StartDate             time.Time  `json:"startDate"`
	EndDate               *time.Time `json:"endDate"`
	Duration              int        `json:"duration"`
	LocationEncryptedBlob []byte     `json:"locationEncryptedBlob"`
	LocationNonce         []byte     `json:"locationNonce"`
}

// Create inserts a new recurring rule and its first meeting occurrence (scheduled at
// the rule's start date). Later occurrences are generated by the recurring meeting
// generator job, which copies the location blob forward from the previous occurrence.
func (s *RecurringRuleService) Create(ctx context.Context, input RecurringRuleInput, userID string) (*Meeting, error) {
	ok, err := db.IsMember(ctx, s.db, input.ChapterID, userID)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: %w", err)
	}
	if !ok {
		return nil, db.ErrNotMember
	}

	var hasActiveRule bool
	err = s.db.QueryRow(ctx, `
		SELECT EXISTS (
			SELECT 1 FROM recurring_rules
			WHERE chapter_id = $1 AND (end_date IS NULL OR end_date > now())
		)
	`, input.ChapterID).Scan(&hasActiveRule)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: check existing rule: %w", err)
	}
	if hasActiveRule {
		return nil, ErrRecurringRuleExists
	}

	ruleID, err := crypto.GenerateID()
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: generate rule ID: %w", err)
	}

	tx, err := s.db.Begin(ctx)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: begin transaction: %w", err)
	}
	defer tx.Rollback(ctx) // no-op if tx.Commit() is called below

	_, err = tx.Exec(ctx, `
		INSERT INTO recurring_rules (id, chapter_id, frequency, interval, start_date, end_date, duration, created_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, now())
	`, ruleID, input.ChapterID, input.Frequency, input.Interval, input.StartDate, input.EndDate, input.Duration)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: insert rule: %w", err)
	}

	meetingID, err := crypto.GenerateID()
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: generate meeting ID: %w", err)
	}

	var m Meeting
	err = tx.QueryRow(ctx, `
		INSERT INTO meetings (id, chapter_id, duration, scheduled_at, recurring_group_id,
			created_at, updated_at, status, location_encrypted_blob, location_nonce)
		VALUES ($1, $2, $3, $4, $5, now(), now(), 'SCHEDULED', $6, $7)
		RETURNING id, chapter_id, duration, scheduled_at, status, recurring_group_id
	`, meetingID, input.ChapterID, input.Duration, input.StartDate, ruleID,
		input.LocationEncryptedBlob, input.LocationNonce).
		Scan(&m.ID, &m.ChapterID, &m.Duration, &m.ScheduledAt, &m.Status, &m.RecurringGroupId)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: insert first meeting: %w", err)
	}

	if err := tx.Commit(ctx); err != nil {
		return nil, fmt.Errorf("RecurringRuleService.Create: commit: %w", err)
	}

	m.LocationEncryptedBlob = input.LocationEncryptedBlob
	m.LocationNonce = input.LocationNonce
	return &m, nil
}

// RecurringRule is the client-facing representation of a recurring_rules row.
type RecurringRule struct {
	ID        string     `json:"id"`
	ChapterID string     `json:"chapterId"`
	Frequency string     `json:"frequency"`
	Interval  int        `json:"interval"`
	StartDate time.Time  `json:"startDate"`
	EndDate   *time.Time `json:"endDate"`
	Duration  int        `json:"duration"`
}

// GetByID fetches a recurring rule, verifying the caller belongs to its chapter.
func (s *RecurringRuleService) GetByID(ctx context.Context, ruleID string, userID string) (*RecurringRule, error) {
	var rule RecurringRule
	err := s.db.QueryRow(ctx, `
		SELECT r.id, r.chapter_id, r.frequency, r.interval, r.start_date, r.end_date, r.duration
		FROM recurring_rules r
		JOIN chapter_members cm ON cm.chapter_id = r.chapter_id AND cm.user_id = $2
		WHERE r.id = $1
	`, ruleID, userID).
		Scan(&rule.ID, &rule.ChapterID, &rule.Frequency, &rule.Interval, &rule.StartDate, &rule.EndDate, &rule.Duration)
	if err != nil {
		return nil, fmt.Errorf("RecurringRuleService.GetByID: %w", err)
	}
	return &rule, nil
}

